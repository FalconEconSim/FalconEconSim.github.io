/* nav.js: the course navigation, in one place.
 *
 * WHAT THIS REPLACES
 * The same 136-line <nav class="left-nav"> block was pasted into 63 pages, with
 * the only per-page difference being which item carried `active`/`on`. Editing
 * the navigation meant editing 63 files, and the block was styled entirely in
 * v1 tokens that no longer matched anything around it.
 *
 * WHY JAVASCRIPT
 * This is a static GitHub Pages site with no include mechanism, so the choice
 * is one JS source or 63 copies. The fallback is real, not theoretical: the
 * topbar carries a plain <a href="index.html"> wordmark that needs no script,
 * and index.html lists every week. With JS off you can still reach everything.
 *
 * STRUCTURE IS DERIVED FROM WHAT EXISTS
 * WEEKS below was generated by listing the files actually on disk, so a link
 * here cannot point at a page that does not exist (antislop R-24). Adding
 * week5-practice.html means adding one line here, and every page gets it.
 *
 * KEYBOARD (antislop R-32)
 * The panel is a modal drawer, so it behaves like one: focus moves into it on
 * open, is trapped while it is open, returns to the trigger on close, and
 * Escape closes it. Week groups are <button aria-expanded>, not <details>, so
 * their state is announced. Every focusable element has a visible focus ring
 * (see .wknav :focus-visible in shared.css).
 */
(function () {
  "use strict";
  if (window.__ec224Nav) return;
  window.__ec224Nav = true;

  /* Unit boundaries: which week each unit starts at, and the unit's name.
     Matches the four unit bands on index.html. */
  var UNITS = [
    { from: 1,  name: "Consumer theory" },
    { from: 5,  name: "Producer theory" },
    { from: 8,  name: "Market structure" },
    { from: 11, name: "Welfare & extensions" }
  ];

  /* n     week number
     title the week's own title, same string as the homepage card
     parts  which component pages exist for that week, in reading order */
  var WEEKS = [
    { n: 1,  title: "Foundations of Microeconomics",                     parts: ["flashcards"] },
    { n: 2,  title: "Indifference Curves & the Consumer Optimum",        parts: ["viz", "practice", "slides", "videos", "flashcards"] },
    { n: 3,  title: "Demand Curves & Comparative Statics",               parts: ["viz", "practice", "slides", "videos", "flashcards"] },
    { n: 4,  title: "Elasticity & Consumer Welfare",                     parts: ["viz", "practice", "slides", "videos", "flashcards"] },
    { n: 5,  title: "Production Theory",                                 parts: ["viz", "slides", "flashcards"] },
    { n: 6,  title: "Cost Theory",                                       parts: ["viz", "slides", "flashcards"] },
    { n: 7,  title: "Profit Maximization & the Competitive Firm",        parts: ["viz", "slides", "flashcards"] },
    { n: 8,  title: "Welfare, Monopoly & Price Discrimination",          parts: ["viz", "flashcards"] },
    { n: 9,  title: "Non-Linear Pricing, Natural Monopoly & Game Theory", parts: ["viz", "flashcards"] },
    { n: 10, title: "Oligopoly Models & Spatial Competition",            parts: ["viz", "flashcards"] },
    { n: 11, title: "Public Goods & Externalities",                      parts: ["viz", "flashcards"] },
    { n: 12, title: "Adverse Selection & Moral Hazard",                  parts: ["viz", "flashcards"] }
  ];

  var PART_LABEL = {
    viz:        "Visualizations",
    practice:   "Practice",
    slides:     "Slides",
    videos:     "Videos",
    flashcards: "Flashcards"
  };

  var here = (location.pathname.split("/").pop() || "index.html").toLowerCase();

  function href(n, part) {
    return "week" + n + (part ? "-" + part : "") + ".html";
  }
  function unitOf(n) {
    var u = 1;
    for (var i = 0; i < UNITS.length; i++) if (n >= UNITS[i].from) u = i + 1;
    return u;
  }
  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  /* ---- build ------------------------------------------------------------ */

  var scrim = el("div", "wknav-scrim");
  scrim.hidden = true;

  var nav = el("nav", "wknav");
  nav.id = "wknav";
  nav.setAttribute("aria-label", "Course weeks");

  var hd = el("div", "wknav-hd");
  var hdTitle = el("span", "wknav-brand", "All weeks");
  var closeBtn = el("button", "wknav-close");
  closeBtn.type = "button";
  closeBtn.setAttribute("aria-label", "Close course navigation");
  closeBtn.innerHTML =
    '<svg viewBox="0 0 20 20" width="18" height="18" fill="none" stroke="currentColor" ' +
    'stroke-width="1.8" stroke-linecap="round" aria-hidden="true">' +
    '<path d="M5 5l10 10M15 5L5 15"/></svg>';
  hd.appendChild(hdTitle);
  hd.appendChild(closeBtn);
  nav.appendChild(hd);

  var list = el("ol", "wknav-list");
  var lastUnit = 0;

  WEEKS.forEach(function (w) {
    var u = unitOf(w.n);
    if (u !== lastUnit) {
      var band = el("li", "wknav-unit");
      band.setAttribute("aria-hidden", "true");
      band.appendChild(el("span", "wknav-unit-n", "Unit " + u));
      band.appendChild(el("span", "wknav-unit-name", UNITS[u - 1].name));
      list.appendChild(band);
      lastUnit = u;
    }

    var overviewHref = href(w.n);
    var item = el("li", "wknav-wk");
    item.dataset.unit = String(u);

    /* Whether this week contains the page currently open. */
    var pageHrefs = [overviewHref].concat(w.parts.map(function (p) { return href(w.n, p); }));
    var isCurrentWeek = pageHrefs.indexOf(here) !== -1;
    if (isCurrentWeek) item.classList.add("is-current");

    var subId = "wknav-sub-" + w.n;

    var btn = el("button", "wknav-wk-btn");
    btn.type = "button";
    btn.setAttribute("aria-expanded", isCurrentWeek ? "true" : "false");
    btn.setAttribute("aria-controls", subId);
    btn.appendChild(el("span", "wknav-n", w.n < 10 ? "0" + w.n : String(w.n)));
    btn.appendChild(el("span", "wknav-wk-name", w.title));
    var caret = el("span", "wknav-caret");
    caret.setAttribute("aria-hidden", "true");
    btn.appendChild(caret);
    item.appendChild(btn);

    var sub = el("ul", "wknav-sub");
    sub.id = subId;
    sub.hidden = !isCurrentWeek;

    [null].concat(w.parts).forEach(function (part) {
      var li = el("li");
      var a = el("a", null, part ? PART_LABEL[part] : "Overview");
      a.href = href(w.n, part);
      if (a.getAttribute("href").toLowerCase() === here) {
        a.setAttribute("aria-current", "page");
        a.classList.add("is-here");
      }
      li.appendChild(a);
      sub.appendChild(li);
    });

    item.appendChild(sub);

    btn.addEventListener("click", function () {
      var open = btn.getAttribute("aria-expanded") === "true";
      btn.setAttribute("aria-expanded", open ? "false" : "true");
      sub.hidden = open;
    });

    list.appendChild(item);
  });

  nav.appendChild(list);

  var askItem = el("div", "wknav-foot");
  var askLink = el("a", "wknav-ask", "Ask the course AI");
  askLink.href = "ask.html";
  if (here === "ask.html") askLink.setAttribute("aria-current", "page");
  askItem.appendChild(askLink);
  nav.appendChild(askItem);

  /* ---- open / close ----------------------------------------------------- */

  var lastTrigger = null;

  function focusables() {
    return Array.prototype.filter.call(
      nav.querySelectorAll("a[href], button:not([disabled])"),
      function (n) { return n.offsetParent !== null; }
    );
  }

  function open(trigger) {
    lastTrigger = trigger || document.activeElement;
    scrim.hidden = false;
    nav.classList.add("is-open");
    document.documentElement.classList.add("wknav-lock");
    var f = focusables();
    /* Land on the current page's link when there is one, so a keyboard user
       arrives where they already are rather than at the top of a 12-week list. */
    var hereLink = nav.querySelector(".wknav-sub a.is-here");
    (hereLink || f[0] || closeBtn).focus();
    document.addEventListener("keydown", onKeydown, true);
  }

  function close() {
    nav.classList.remove("is-open");
    scrim.hidden = true;
    document.documentElement.classList.remove("wknav-lock");
    document.removeEventListener("keydown", onKeydown, true);
    if (lastTrigger && document.contains(lastTrigger)) lastTrigger.focus();
    lastTrigger = null;
  }

  function onKeydown(e) {
    if (e.key === "Escape") { e.preventDefault(); close(); return; }
    if (e.key !== "Tab") return;
    var f = focusables();
    if (!f.length) return;
    var first = f[0], last = f[f.length - 1];
    if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
    else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
  }

  closeBtn.addEventListener("click", function () { close(); });
  scrim.addEventListener("click", function () { close(); });

  /* ---- mount ------------------------------------------------------------ */

  function mount() {
    document.body.appendChild(scrim);
    document.body.appendChild(nav);

    /* Any element opting in becomes a trigger. The pages currently ship
       <button class="btn" onclick="openLN()">All weeks</button>; the sweep that
       removed the inline markup rewrites those to data-nav-open. */
    Array.prototype.forEach.call(
      document.querySelectorAll("[data-nav-open]"),
      function (t) {
        t.setAttribute("aria-controls", "wknav");
        t.addEventListener("click", function (e) { e.preventDefault(); open(t); });
      }
    );
  }

  /* Kept as aliases so any page still carrying the old inline handler keeps
     working instead of throwing. Remove once no page references them. */
  window.openLN = function () { open(null); };
  window.closeLN = close;

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", mount);
  } else {
    mount();
  }
})();
